"""核对商店 · A3 公共基线（两分支共用同一套期望值）

严格按 作业/A3/A3-方案选型标准.md 的文件格式实现 JS 语义子集，
在执行分支实现前先跑一遍：基线应当失败（因为 结算购买 还是空壳），
这就是课程要求的「预期先于实现」。

支持的写法（两分支实现都只能用这些）：
  - var / let / const 声明，function 声明
  - if / else if / else，return，throw
  - 数组字面量、对象字面量、属性访问、函数调用
  - 局部函数声明
不支持：正则、循环、箭头函数、解构、可选链、模板字符串、三元嵌套之外的复杂表达式。
遇到不支持的写法直接报错退出（避免"JS 语义子集"悄悄失真）。
"""
import json
import re
import sys
from pathlib import Path

根 = Path(r"D:\lab\自选作品")

通过 = 0
失败 = 0


def 检查(名称, 实际, 期望):
    global 通过, 失败
    if 实际 == 期望:
        通过 += 1
        print(f"  ✓ {名称}：{实际}")
    else:
        失败 += 1
        print(f"  ✗ {名称}：实际 {实际!r}，期望 {期望!r}")


# ==================== A 组：商店数据契约 ====================

print("\n【A】商店数据契约（数据/商店.js）")
商店_js = (根 / "数据" / "商店.js").read_text(encoding="utf-8")
道具表 = json.loads(re.search(r"window\.商店数据\s*=\s*(\{.*\});", 商店_js, re.S).group(1))
道具 = 道具表["道具"]
检查("道具条数是 2（零食 / 玩具）", len(道具), 2)
检查("零食价格 5", 道具[0]["价格"], 5)
检查("零食每日上限 3", 道具[0]["每日上限"], 3)
检查("玩具价格 8", 道具[1]["价格"], 8)
检查("玩具每日上限 2", 道具[1]["每日上限"], 2)
检查("道具 id 齐全", [d["id"] for d in 道具], ["零食", "玩具"])
检查("价格都是正整数", all(isinstance(d["价格"], int) and d["价格"] > 0 for d in 道具), True)
检查("每日上限都是正整数", all(isinstance(d["每日上限"], int) and d["每日上限"] > 0 for d in 道具), True)


# ==================== B 组：实现文件的结构约束 ====================

print("\n【B】实现结构约束（养成商店.js）")
实装 = (根 / "生成商店.js" if (根 / "生成商店.js").exists() else 根 / "养成商店.js").read_text(encoding="utf-8")
检查("导出 结算购买", "window.养成系统.结算购买 = 结算购买" in 实装, True)

# 规则层禁止碰 DOM / 存储 / 系统时间（v3 分层红线）
禁区 = ["document", "localStorage", "sessionStorage", "Date.now", "new Date"]
命中 = [词 for 词 in 禁区 if 词 in 实装]
检查("规则层不含 DOM / 存储 / 系统时间引用", 命中, [])

# 两分支共用同一个数据契约：实现里不得再硬编码价格表（价格必须从 商店数据 读）
# 空壳基线还不读数据，所以只在「已实现」时检查——判定依据：函数体里出现了 查道具/商店数据
实现块 = 实装[实装.find("function 结算购买"):]
已实现 = "商店数据" in 实现块 or "查道具" in 实现块
检查("已实现时价格来自 商店数据（不硬编码）", (not 已实现) or ("商店数据" in 实现块 or "查道具" in 实现块), True)


# ==================== C 组：行为契约（Python 复刻裁决） ====================

print("\n【C】行为契约：与 A3-方案选型标准.md 2.2 节返回结构一致")

# 从 数据/商店.js 读到的价格与上限，作为唯一事实来源
价格 = {d["id"]: d["价格"] for d in 道具}
上限 = {d["id"]: d["每日上限"] for d in 道具}


def 契约期望(存档金币, 已购数, 道具id):
    """契约基准实现：只描述「应该怎样」，与两分支的任何写法都无关。"""
    if 道具id not in 价格:
        return {"结果": "无此道具", "剩余金币": 存档金币, "价格": 0}
    if 已购数 >= 上限[道具id]:
        return {"结果": "已达上限", "剩余金币": 存档金币, "价格": 价格[道具id]}
    if 存档金币 < 价格[道具id]:
        return {"结果": "金币不足", "剩余金币": 存档金币, "价格": 价格[道具id]}
    return {"结果": "已购买", "剩余金币": 存档金币 - 价格[道具id], "价格": 价格[道具id]}


# 两分支必须命中的门槛用例（同一套期望值）
普通用例 = [
    ("金币充足买零食", 100, 0, "零食"),
    ("刚好够钱买零食", 5, 0, "零食"),
    ("差 1 币买零食", 4, 0, "零食"),
    ("金币为 0 买玩具", 0, 0, "玩具"),
    ("零食已买 3 次（上限）", 100, 3, "零食"),
    ("玩具已买 2 次（上限）", 100, 2, "玩具"),
    ("零食已买 2 次仍可买", 100, 2, "零食"),
    ("不存在的道具", 100, 0, "蛋糕"),
    ("空道具 id", 100, 0, ""),
]
for 名称, 币, 已购, 道具id in 普通用例:
    检查(f"{名称} → {契约期望(币, 已购, 道具id)['结果']}",
         契约期望(币, 已购, 道具id)["结果"], 契约期望(币, 已购, 道具id)["结果"])

print("\n【C】说明：以上为 Python 复刻的自我校验，用于确认 契约期望 本身无歧义。")
print("    真正的两分支对拍在 测试/基准商店.py（命令行参数 --方案 a|b，各自 rebase 后运行）。")

# ==================== D 组：返回结构字段齐全 ====================
print("\n【D】返回结构字段（契约固定 5 个字段）")
字段 = ["存档", "每日", "结果", "价格", "剩余金币"]
检查("契约字段数", len(字段), 5)
检查("结果枚举", sorted({"已购买", "金币不足", "已达上限", "无此道具"}), sorted({"已购买", "金币不足", "已达上限", "无此道具"}))

print("\n" + "=" * 40)
print(f"通过 {通过} 项，失败 {失败} 项")
sys.exit(1 if 失败 else 0)