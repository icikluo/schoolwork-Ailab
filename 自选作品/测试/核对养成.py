def 复制存档(a):
    r = dict(a or {})
    r["版本"] = r.get("版本") or 1
    r["经验"] = max(0, r.get("经验") or 0)
    r["金币"] = max(0, r.get("金币") or 0)
    r["形象"] = dict(r.get("形象") or {})
    r["已购"] = list(r.get("已购") or [])
    r["宠物"] = dict(r["宠物"]) if r.get("宠物") else None
    r["上次打卡日"] = r.get("上次打卡日") or None
    r["连续天数"] = max(0, r.get("连续天数") or 0)
    return r


def 复制每日(d):
    r = dict(d or {})
    r["三餐"] = list(r.get("三餐") or [])
    r["喝水"] = max(0, r.get("喝水") or 0)
    r["运动"] = max(0, r.get("运动") or 0)
    r["已喂宠物"] = bool(r.get("已喂宠物"))
    r["达标"] = bool(r.get("达标"))
    return r


def 结算打卡(存档, 每日, 来源, 额外=None):
    e = 额外 or {}
    新存档 = 复制存档(存档)
    新每日 = 复制每日(每日)
    今天 = e.get("今天") or 新每日.get("日期") or None

    def 返回(结果, 获得经验=0, 获得金币=0, 升级数=0, 刚达标=False):
        return {"存档": 新存档, "每日": 新每日,
                "获得": {"经验": 获得经验, "金币": 获得金币},
                "结果": 结果, "升了几级": 升级数, "是否刚达标": 刚达标}

    归 = 归一化来源(来源, 新每日, e)
    if 归["结果"]:
        return 返回(归["结果"])
    s = 归["来源"]

    if s in 三餐 and s in 新每日["三餐"]:
        return 返回("已完成")
    if s == "喝水" and 新每日["喝水"] >= 每日上限["喝水"]:
        return 返回("已上限")
    if s == "运动" and 新每日["运动"] >= 每日上限["运动"]:
        return 返回("已上限")
    if s == "达标" and 新每日["达标"]:
        return 返回("已完成")

    if s in 三餐:
        新每日["三餐"].append(s)
    elif s == "喝水":
        新每日["喝水"] += 1
    elif s == "运动":
        新每日["运动"] += 1
    elif s == "达标":
        新每日["达标"] = True

    奖 = 奖励表[s]
    加成 = max(0, min(e["家具加成"], 家具加成上限)) if isinstance(e.get("家具加成"), (int, float)) else 0
    本次经验 = 奖["经验"]
    本次金币 = round(奖["金币"] * (1 + 加成))

    旧经验 = 新存档["经验"]
    新存档["经验"] = 旧经验 + 本次经验
    新存档["金币"] += 本次金币

    if s != "达标" and 今天:
        新存档["连续天数"] = 更新连续天数(新存档["上次打卡日"], 今天, 新存档["连续天数"])
        新存档["上次打卡日"] = 今天

    升了几级 = 由经验算等级(新存档["经验"])["等级"] - 由经验算等级(旧经验)["等级"]

    刚达标 = False
    if s != "达标" and not 新每日["达标"] and 每日是否达标(新每日, e.get("目标") or 每日目标):
        递归 = 结算打卡(新存档, 新每日, "达标",
                      {"今天": 今天, "家具加成": 加成, "目标": e.get("目标")})
        新存档, 新每日 = 递归["存档"], 递归["每日"]
        本次经验 += 递归["获得"]["经验"]
        本次金币 += 递归["获得"]["金币"]
        升了几级 += 递归["升了几级"]
        刚达标 = True

    return 返回("已达标" if 刚达标 or s == "达标" else "已完成",
                本次经验, 本次金币, 升了几级, 刚达标)


def 宠物心情(每日, 存档, 额外=None):
    d, a, e = 每日 or {}, 存档 or {}, 额外 or {}
    完成数 = sum([bool(d.get("三餐")), (d.get("喝水") or 0) > 0, (d.get("运动") or 0) > 0])
    心情 = "开心" if 每日是否达标(d, e.get("目标") or 每日目标) else ("一般" if 完成数 >= 1 else "有点想你")
    亲密 = ((a.get("宠物") or {}).get("亲密度") or 0)
    if e.get("今天喂过"):
        亲密 = min(100, 亲密 + 5)
    return {"心情": 心情, "亲密度": max(0, 亲密), "完成项数": 完成数}


def 复制场景(s):
    r = dict(s or 默认场景())
    r["相机"] = dict(r.get("相机") or {"yaw": 0})
    家具列表 = list(r.get("家具") or [])[:6]
    while len(家具列表) < 6:
        家具列表.append(None)
    r["家具"] = [dict(项) if 项 else None for 项 in 家具列表]
    return r


def 场景槽位表(数据表=None):
    表 = 数据表 if 数据表 is not None else 家具
    return [{"槽": i, "id": 件["id"], "x": 件["默认位置"]["x"], "z": 件["默认位置"]["z"]}
            for i, 件 in enumerate(表)]


def 摆放家具(场景, 槽, 家具id, 数据表=None):
    s = 复制场景(场景)
    表 = 数据表 if 数据表 is not None else 家具
    if not isinstance(槽, int) or not (0 <= 槽 <= 5):
        return {"场景": s, "结果": "槽位无效"}
    找到 = next((件 for 件 in 表 if 件["id"] == 家具id), None)
    if not 找到:
        return {"场景": s, "结果": "无此家具"}
    if any(j != 槽 and s["家具"][j] and s["家具"][j]["id"] == 家具id for j in range(6)):
        return {"场景": s, "结果": "重复"}
    s["家具"][槽] = {"槽": 槽, "id": 家具id,
                    "x": 找到["默认位置"]["x"], "z": 找到["默认位置"]["z"]}
    return {"场景": s, "结果": "已摆放"}


def 收起家具(场景, 槽):
    s = 复制场景(场景)
    if isinstance(槽, int) and 0 <= 槽 <= 5:
        s["家具"][槽] = None
    return {"场景": s, "结果": "已收起"}


def 场景加成(场景, 数据表=None):
    return 家具加成((场景 or {}).get("家具"), 数据表)


