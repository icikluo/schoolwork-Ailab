def 家具加成(家具列表=None, 数据表=None):
    表 = 数据表 if 数据表 is not None else 家具
    见过, 总 = set(), 0.0
    for 项 in (家具列表 or []):
        if not 项:
            continue
        id = 项 if isinstance(项, str) else 项.get("id")
        if not id or id in 见过:
            continue
        见过.add(id)
        for 件 in 表:
            if 件["id"] == id:
                总 += 件["加成"]
                break
    return min(总, 家具加成上限)


