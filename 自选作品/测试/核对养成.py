def 读JS对象(文件名, 变量名):
    """从 window.xxx = {...}; 里截出 JSON 并解析（跳过字符串内的引号）。"""
    文本 = (根 / 文件名).read_text(encoding="utf-8")
    起点 = 文本.index(变量名 + " =") + len(变量名 + " =")
    while 文本[起点].isspace():
        起点 += 1
    assert 文本[起点] in "{[", 文件名
    深度 = 0
    串内 = False
    引号 = None
    转义 = False
    for i in range(起点, len(文本)):
        c = 文本[i]
        if 串内:
            if 转义:
                转义 = False
                continue
            if c == "\\":
                转义 = True
                continue
            if c == 引号:
                串内 = False
            continue
        if c in "\"'":
            串内 = True
            引号 = c
            continue
        if c in "{[":
            深度 += 1
        elif c in "}]":
            深度 -= 1
            if 深度 == 0:
                return json.loads(文本[起点:i + 1])
    raise ValueError(f"{文件名} 未找到对象结尾")


