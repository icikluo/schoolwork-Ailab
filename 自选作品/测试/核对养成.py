def 升级所需经验(等级):
    return float("inf") if 等级 >= 满级 else 100 + (等级 - 1) * 100


def 由经验算等级(总经验):
    经验 = max(0, 总经验)
    等级, 累计 = 1, 0
    while 等级 < 满级 and 经验 >= 累计 + 升级所需经验(等级):
        累计 += 升级所需经验(等级)
        等级 += 1
    if 等级 >= 满级:
        return {"等级": 满级, "级内经验": 0, "升级需要": 0, "剩余": 0,
                "是否满级": True, "累计经验": 满级累计经验,
                "星星": max(0, (经验 - 满级累计经验) // 每星经验)}
    需要 = 升级所需经验(等级)
    级内 = 经验 - 累计
    return {"等级": 等级, "级内经验": 级内, "升级需要": 需要,
            "剩余": 需要 - 级内, "是否满级": False, "累计经验": 累计, "星星": 0}


def 星级(总经验):
    return 由经验算等级(总经验)["星星"]


def 相差天数(起, 止):
    try:
        a = date.fromisoformat(起)
        b = date.fromisoformat(止)
    except (ValueError, TypeError):
        return None
    return (b - a).days


def 更新连续天数(上次日期, 今天, 当前连续天数):
    当前 = max(0, 当前连续天数 or 0)
    if not 上次日期:
        return 1
    if 上次日期 == 今天:
        return max(当前, 1)
    差 = 相差天数(上次日期, 今天)
    if 差 is None or 差 <= 0:
        return max(当前, 1)
    if 差 == 1:
        return 当前 + 1
    return 1


def 校验餐次时间窗(餐次, 小时):
    return any(起 <= 小时 < 止 for 起, 止 in 餐次时间窗.get(餐次, []))


def 归一化来源(来源, 每日, 额外=None):
    e = 额外 or {}
    d = 每日 or {}
    if 来源 == "加餐":
        if "晚" not in (d.get("三餐") or []):
            return {"来源": "晚", "结果": None, "兜底": True}
        return {"来源": None, "结果": "不打卡", "兜底": False}
    if 来源 not in 合法来源:
        return {"来源": None, "结果": "无效来源", "兜底": False}
    if e.get("强制") and 来源 in 三餐 and isinstance(e.get("小时"), (int, float)):
        if not 校验餐次时间窗(来源, e["小时"]):
            return {"来源": None, "结果": "未到餐点", "兜底": False}
    return {"来源": 来源, "结果": None, "兜底": False}


