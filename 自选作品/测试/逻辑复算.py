def 生成一周计划(人群, 每日目标, 食谱=None):
    """与 脚本.js 的 生成一周计划() 保持一致。

    约束优先级：
      1) 每天合计绝不超过目标（硬约束）
      2) 每天尽量吃够目标（早餐 30% / 午餐 40% / 晚餐 30% 配额）
      3) 尽量少重复（权重最低）

    打分制：分数 = 与目标卡路里接近度 + 重复罚 - 间隔奖，分越低越优先。
    """
    全部 = 食谱 if 食谱 is not None else 数据
    使用次数 = {}
    上次出现天 = {}
    天数 = []
    餐份量 = [0.35, 0.35, 0.3]
    本群体菜 = [c for c in 全部 if 人群 in c["人群"]]

    for d in range(计划天数):
        当日餐 = []
        当日已用ids = []
        当日卡路里 = 0
        餐配额 = [每日目标 * x for x in 餐份量]

        for m in range(len(每日餐次)):
            剩余 = 每日目标 - 当日卡路里
            if 剩余 <= 0:
                break
            # 目标卡 = 本餐配额 + 前面没吃够的余量分摊，避免全天吃不够
            前面欠的 = max(sum(餐配额[:m]) - 当日卡路里, 0)
            目标卡 = min(餐配额[m] + 前面欠的 * 0.6, 剩余)
            # 单餐硬上限：不超日额度 45%，且给后面每餐留至少 200 kcal
            后续餐数 = len(每日餐次) - m - 1
            单餐上限 = min(每日目标 * 0.45, 剩余 - 后续餐数 * 200)

            候选 = [c for c in 本群体菜
                  if c["id"] not in 当日已用ids and c["卡路里"] <= 单餐上限]
            # 没有未用过的合适菜时允许当日重复（排满三餐优先）
            if not 候选:
                候选 = [c for c in 本群体菜 if c["卡路里"] <= 单餐上限]
            # 仍无合适菜时只受剩余额度约束
            if not 候选:
                候选 = [c for c in 本群体菜 if c["卡路里"] <= 剩余]
            if not 候选:
                break

            def _分(c):
                卡差 = abs(c["卡路里"] - 目标卡) / 每日目标
                重复罚 = 使用次数.get(c["id"], 0) * 0.20
                间隔奖 = (0 if c["id"] not in 上次出现天
                        else min(d - 上次出现天[c["id"]], 3) * 0.05)
                return 卡差 + 重复罚 - 间隔奖

            候选.sort(key=_分)
            选中 = 候选[0]
            当日餐.append({"餐次": 每日餐次[m], "id": 选中["id"],
                       "名称": 选中["名称"], "卡路里": 选中["卡路里"]})
            当日已用ids.append(选中["id"])
            使用次数[选中["id"]] = 使用次数.get(选中["id"], 0) + 1
            上次出现天[选中["id"]] = d
            当日卡路里 += 选中["卡路里"]
        天数.append({"序号": d + 1, "名称": f"第 {d+1} 天",
                   "餐": 当日餐, "卡路里合计": round(当日卡路里)})
    return {"人群": 人群, "每日目标": 每日目标, "天数": 天数}


