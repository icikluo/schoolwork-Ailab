def 结转历史(今日记录, 存日期, 今日, 历史):
    """复刻 脚本.js 结转历史 + 截断历史：日期变了才结转，历史只留 7 天"""
    if not 存日期:
        return 今日记录, 历史, 今日
    if 存日期 == 今日:
        return 今日记录, 历史, 存日期
    if 今日记录:
        历史 = dict(历史)
        历史[存日期] = 今日记录
        键集 = sorted(历史)
        while len(键集) > 7:
            del 历史[键集.pop(0)]
    return [], 历史, 今日


