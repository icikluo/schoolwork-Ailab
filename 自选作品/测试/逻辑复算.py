def 过滤排序(食谱, 关键词, 排序):
    """复刻 脚本.js 渲染专区 的过滤与排序"""
    待显示 = list(食谱)
    if 关键词:
        待显示 = [c for c in 待显示 if 关键词 in c["名称"]]
    if 排序 == "热量升":
        待显示.sort(key=lambda c: (c["卡路里"], c["id"]))
    elif 排序 == "热量降":
        待显示.sort(key=lambda c: (-c["卡路里"], c["id"]))
    else:
        待显示.sort(key=lambda c: c["id"])
    return 待显示


