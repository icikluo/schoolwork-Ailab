def 折算份量(菜, 份量):
    """复刻 脚本.js 同名函数：半份 0.5 / 整份 1，卡路里取整、克数 1 位小数"""
    份量 = 0.5 if 份量 == 0.5 else 1
    结果 = {"卡路里": int(菜["卡路里"] * 份量 + 0.5)}
    for k in ["碳水", "脂肪", "膳食纤维", "蛋白质"]:
        结果[k] = int(菜[k] * 份量 * 10 + 0.5) / 10
