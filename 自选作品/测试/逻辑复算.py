print("\n【8】一周计划：只生成 7 天，不生成 30 天")
计划天数 = 7
每日餐次 = ["早", "午", "晚"]


def 生成一周计划(人群, 每日目标, 食谱=None):
    """与 脚本.js 的 生成一周计划() 保持一致。

    硬约束：同一天内不重复；单餐不超过当日剩余额度。
    """
    全部 = 食谱 if 食谱 is not None else 数据
    已用ids = []
    天数 = []
    for d in range(计划天数):
        当日餐 = []
        当日卡路里 = 0
        当日已用 = []
        for m in range(len(每日餐次)):
            剩余 = 每日目标 - 当日卡路里
            if 剩余 <= 100:
                break
            餐预算 = 剩余 / (len(每日餐次) - m)
            候选 = [c for c in 全部
                  if 人群 in c["人群"]
                  and c["id"] not in 已用ids
                  and c["id"] not in 当日已用
                  and c["卡路里"] <= 剩余]
            if not 候选:
                候选 = [c for c in 全部
                      if 人群 in c["人群"]
                      and c["id"] not in 当日已用
                      and c["卡路里"] <= 剩余]
                if not 候选:
                    break
            候选.sort(key=lambda c: abs(c["卡路里"] - 餐预算))
            选中 = 候选[0]
            当日餐.append({"餐次": 每日餐次[m], "id": 选中["id"],
                       "名称": 选中["名称"], "卡路里": 选中["卡路里"]})
            当日已用.append(选中["id"])
            已用ids.append(选中["id"])
            当日卡路里 += 选中["卡路里"]
        天数.append({"序号": d + 1, "名称": f"第 {d+1} 天",
                   "餐": 当日餐, "卡路里合计": round(当日卡路里)})
    return {"人群": 人群, "每日目标": 每日目标, "天数": 天数}


