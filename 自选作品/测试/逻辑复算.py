def 向上取整(x):
    """复刻 JS Math.round：0.5 一律向上（Python round 是银行家舍入，不能直接用）"""
    return int(x + 0.5)


def 计算宏量目标(目标卡路里, 人群):
    比 = 宏量供能比[人群]
    return {k: 向上取整(目标卡路里 * 比[k] / 供能系数[k]) for k in 供能系数}


