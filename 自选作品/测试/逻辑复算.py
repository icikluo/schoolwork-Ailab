import re as _re


def 从文本提取JSON(文本):
    """复刻 脚本.js 同名函数：容忍 ```json 围栏与前后废话，失败返回 None"""
    净 = _re.sub(r"```json", "", str(文本 or ""), flags=_re.I).replace("```", "").strip()
    首 = 净.find("{")
    尾 = 净.rfind("}")
    if 首 == -1 or 尾 == -1 or 尾 <= 首:
        return None
    try:
        return json.loads(净[首:尾 + 1])
    except ValueError:
        return None


def 保留一位小数(x):
    return int(x * 10 + 0.5) / 10


def 校验AI菜品(对象):
    """复刻 脚本.js 同名函数：字段齐全且数值在 5.3 契约区间内才放行"""
    if not isinstance(对象, dict):
        return None
    名称 = 对象.get("名称")
    if not isinstance(名称, str) or not 名称.strip():
        return None
    菜 = {"名称": 名称.strip()[:20]}
    for 字段 in ["卡路里", "碳水", "脂肪", "膳食纤维", "蛋白质"]:
        try:
            菜[字段] = float(对象[字段])
        except (TypeError, ValueError, KeyError):
            return None
    if 菜["卡路里"] < 0 or 菜["卡路里"] > 3000:
        return None
    for 字段 in ["碳水", "脂肪", "膳食纤维", "蛋白质"]:
        if 菜[字段] < 0 or 菜[字段] > 500:
            return None
    菜["卡路里"] = int(菜["卡路里"] + 0.5)
    for 字段 in ["碳水", "脂肪", "膳食纤维", "蛋白质"]:
        菜[字段] = 保留一位小数(菜[字段])
    return 菜


def 校验AI推荐(对象, 菜单, 已记录ids, 剩余额度):
    """复刻 脚本.js 同名函数：id 存在、未吃过、不超额度、去重，宁可少推不硬推"""
    结果 = []
    if not isinstance(对象, dict) or not isinstance(对象.get("推荐"), list):
        return 结果
    索引 = {菜["id"]: 菜 for 菜 in 菜单}
    见过 = []
    for 项 in 对象["推荐"]:
        if not isinstance(项, dict) or not isinstance(项.get("id"), str):
            continue
        菜 = 索引.get(项["id"])
        if 菜 is None or 项["id"] in 见过:
            continue
        if 菜["id"] in 已记录ids or 菜["卡路里"] > 剩余额度:
            continue
        见过.append(菜["id"])
        理由 = 项.get("理由") if isinstance(项.get("理由"), str) else ""
        结果.append({"id": 菜["id"], "理由": 理由[:30]})
    return 结果


