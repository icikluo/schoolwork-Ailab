/* 养成系统 · A3 方案 B：分派表式（feature/plan-b）
 *
 * 契约见 作业/A3/A3-方案选型标准.md 2.2 节：
 *   结算购买(存档, 每日, 道具id, 额外) -> { 存档, 每日, 结果, 价格, 剩余金币 }
 *   结果 ∈ { "已购买", "金币不足", "已达上限", "无此道具" }
 *
 * 实现思路（B 方案）：
 *   1) 按 id 建好索引表，O(1) 取价（避免线性查找）
 *   2) 先把「能否购买」归一成一个统一判定函数 判定()，再用分派表
 *      { 已购买: 执行购买, 金币不足: 原样返回, 已达上限: 原样返回, 无此道具: 原样返回 }
 *      这样新增一种拒绝原因只加一行，不需要改主流程
 *   3) 拒绝分支共用同一条返回语句（少一段重复代码）
 * 优点：新增规则只加分派项；缺点：多一层间接，初读不如平铺 if 直接。
 */
(function () {
  "use strict";

  function 建索引() {
    var 表 = window.商店数据.道具;
    var 索引 = {};
    for (var i = 0; i < 表.length; i++) {
      索引[表[i].id] = 表[i];
    }
    return 索引;
  }

  function 判定(存档, 每日, 道具) {
    if (!道具) return "无此道具";
    if ((每日.购买 && 每日.购买[道具.id] || 0) >= 道具.每日上限) return "已达上限";
    if (存档.金币 < 道具.价格) return "金币不足";
    return "已购买";
  }

  function 结算购买(存档, 每日, 道具id, 额外) {
    var 新存档 = JSON.parse(JSON.stringify(存档));
    var 新每日 = JSON.parse(JSON.stringify(每日));
    var 道具 = 建索引()[道具id];
    var 结论 = 判定(新存档, 新每日, 道具);
    var 价格 = 道具 ? 道具.价格 : 0;

    var 分派 = {
      "已购买": function () {
        新存档.金币 = 新存档.金币 - 价格;
        if (!新存档.宠物) 新存档.宠物 = {};
        if (!新存档.宠物.物品) 新存档.宠物.物品 = {};
        新存档.宠物.物品[道具id] = (新存档.宠物.物品[道具id] || 0) + 1;
        if (!新每日.购买) 新每日.购买 = {};
        新每日.购买[道具id] = (新每日.购买[道具id] || 0) + 1;
      }
    };

    if (分派[结论]) 分派[结论]();

    return {
      "存档": 新存档,
      "每日": 新每日,
      "结果": 结论,
      "价格": 价格,
      "剩余金币": 新存档.金币
    };
  }

  window.养成系统 = window.养成系统 || {};
  window.养成系统.结算购买 = 结算购买;
})();