/* 养成系统 · A3 方案 A：查表式（feature/plan-a）
 *
 * 契约见 作业/A3/A3-方案选型标准.md 2.2 节：
 *   结算购买(存档, 每日, 道具id, 额外) -> { 存档, 每日, 结果, 价格, 剩余金币 }
 *   结果 ∈ { "已购买", "金币不足", "已达上限", "无此道具" }
 *
 * 实现思路（A 方案）：
 *   1) 线性查表拿到价格与每日上限（商品只有 2 种，n 很小）
 *   2) 三段平铺 if：无此道具 → 已达上限 → 金币不足 → 正常购买
 *   3) 每次进入先深拷入参，保证不改动调用方对象
 * 优点：一眼看完，没有间接层；缺点：分支多，圈复杂度略高。
 */
(function () {
  "use strict";

  function 查道具(道具id) {
    var 表 = window.商店数据.道具;
    for (var i = 0; i < 表.length; i++) {
      if (表[i].id === 道具id) return 表[i];
    }
    return null;
  }

  function 结算购买(存档, 每日, 道具id, 额外) {
    var 新存档 = JSON.parse(JSON.stringify(存档));
    var 新每日 = JSON.parse(JSON.stringify(每日));

    var 道具 = 查道具(道具id);
    if (!道具) {
      return { "存档": 新存档, "每日": 新每日, "结果": "无此道具", "价格": 0, "剩余金币": 新存档.金币 };
    }

    var 已购 = 0;
    if (新每日.购买) 已购 = 新每日.购买[道具id] || 0;

    if (已购 >= 道具.每日上限) {
      return { "存档": 新存档, "每日": 新每日, "结果": "已达上限", "价格": 道具.价格, "剩余金币": 新存档.金币 };
    }

    if (新存档.金币 < 道具.价格) {
      return { "存档": 新存档, "每日": 新每日, "结果": "金币不足", "价格": 道具.价格, "剩余金币": 新存档.金币 };
    }

    新存档.金币 = 新存档.金币 - 道具.价格;
    if (!新存档.宠物) 新存档.宠物 = {};
    if (!新存档.宠物.物品) 新存档.宠物.物品 = {};
    新存档.宠物.物品[道具id] = (新存档.宠物.物品[道具id] || 0) + 1;

    if (!新每日.购买) 新每日.购买 = {};
    新每日.购买[道具id] = 已购 + 1;

    return { "存档": 新存档, "每日": 新每日, "结果": "已购买", "价格": 道具.价格, "剩余金币": 新存档.金币 };
  }

  window.养成系统 = window.养成系统 || {};
  window.养成系统.结算购买 = 结算购买;
})();