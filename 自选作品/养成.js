/* 养成系统 · 规则层（v0.6 / M0）
 *
 * 本文件只放纯函数：不碰 DOM、不碰 localStorage、不读系统时间。
 * 所有需要"今天 / 小时 / 家具加成"的地方都由参数注入，便于 测试/核对养成.py 对拍。
 * 对外接口挂在 window.养成系统 上；页面渲染、存储读写由后续里程碑负责。
 *
 * 规则依据：养成系统-方案-v3.md 第 2 / 3 / 4 章（覆盖 DeepSeek 原稿对应条目）。
 */
(function () {
  "use strict";

  var 奖励表 = {
    "早":   { "经验": 20, "金币": 5 },
    "午":   { "经验": 20, "金币": 5 },
    "晚":   { "经验": 20, "金币": 5 },
    "喝水": { "经验": 5,  "金币": 1 },
    "运动": { "经验": 30, "金币": 8 },
    "达标": { "经验": 50, "金币": 20 }
  };

  var 每日目标 = { "三餐": 3, "喝水": 6, "运动": 1 };
  var 每日上限 = { "喝水": 8, "运动": 3 };
  var 合法来源 = ["早", "午", "晚", "喝水", "运动", "达标"];
  var 三餐 = ["早", "午", "晚"];

  // R2：计划页「标记已吃」带强制餐次，必须落在餐次时间窗内才计经验。
  // 晚跨零点；小时按 0–23 整数注入。
  var 餐次时间窗 = {
    "早": [[4, 10]],
    "午": [[10, 15]],
    "晚": [[15, 24], [0, 4]]
  };

  var 满级 = 10;
  var 每星经验 = 500;
  var 家具加成上限 = 0.5;
  var 满级累计经验 = 4500;

  function 浅拷(o) {
    var r = {};
    Object.keys(o || {}).forEach(function (k) { r[k] = o[k]; });
    return r;
  }

  function 空获得() { return { "经验": 0, "金币": 0 }; }

  // ============ 等级曲线 ============

  function 升级所需经验(等级) {
    if (等级 >= 满级) return Infinity;
    return 100 + (等级 - 1) * 100;
  }

  function 由经验算等级(总经验) {
    var 经验 = Math.max(0, Number(总经验) || 0);
    var 等级 = 1, 累计 = 0;
    while (等级 < 满级 && 经验 >= 累计 + 升级所需经验(等级)) {
      累计 += 升级所需经验(等级);
      等级 += 1;
    }
    if (等级 >= 满级) {
      return {
        "等级": 满级, "级内经验": 0, "升级需要": 0, "剩余": 0,
        "是否满级": true, "累计经验": 满级累计经验,
        "星星": Math.max(0, Math.floor((经验 - 满级累计经验) / 每星经验))
      };
    }
    var 需要 = 升级所需经验(等级);
    var 级内 = 经验 - 累计;
    return {
      "等级": 等级, "级内经验": 级内, "升级需要": 需要, "剩余": 需要 - 级内,
      "是否满级": false, "累计经验": 累计, "星星": 0
    };
  }

  function 星级(总经验) { return 由经验算等级(总经验).星星; }

  // ============ 日期与连签 ============

  // 必须按本地时区解析 yyyy-MM-dd；不能用 new Date("2026-11-16")（那是 UTC，会差 8 小时）。
  function 解析日期(文本) {
    var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(文本 || "");
    if (!m) return null;
    return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 0, 0, 0, 0);
  }

  function 相差天数(起, 止) {
    var a = 解析日期(起), b = 解析日期(止);
    if (!a || !b) return NaN;
    return Math.round((b.getTime() - a.getTime()) / 86400000);
  }

  // 断签把计数归 1，但「不扣任何经验 / 等级 / 物品」——这才是红线 1.2 的真正含义。
  // 连签不携带货币价值（R9），所以改系统时间刷它没有收益。
  function 更新连续天数(上次日期, 今天, 当前连续天数) {
    var 当前 = Math.max(0, Number(当前连续天数) || 0);
    if (!上次日期) return 1;
    if (上次日期 === 今天) return Math.max(当前, 1);
    var 差 = 相差天数(上次日期, 今天);
    if (isNaN(差) || 差 <= 0) return Math.max(当前, 1);
    if (差 === 1) return 当前 + 1;
    return 1;
  }

  // ============ 来源判定（R1 加餐兜底 / R2 时间窗） ============

  function 校验餐次时间窗(餐次, 小时) {
    var 窗 = 餐次时间窗[餐次];
    if (!窗) return false;
    for (var i = 0; i < 窗.length; i++) {
      if (小时 >= 窗[i][0] && 小时 < 窗[i][1]) return true;
    }
    return false;
  }

  // 返回 { 来源, 结果, 兜底 }；结果为非 null 时表示本次不打卡。
  function 归一化来源(来源, 每日, 额外) {
    var e = 额外 || {};
    var d = 每日 || {};
    if (来源 === "加餐") {
      // R1：21 点后那一餐，用户语义上就是晚饭；当天还没有「晚」时兜底记为晚。
      if ((d.三餐 || []).indexOf("晚") === -1) {
        return { "来源": "晚", "结果": null, "兜底": true };
      }
      return { "来源": null, "结果": "不打卡", "兜底": false };
    }
    if (合法来源.indexOf(来源) === -1) {
      return { "来源": null, "结果": "无效来源", "兜底": false };
    }
    // R2：只有「强制餐次」（计划页标记已吃）才校验时间窗；注入小时才校验，保持纯函数。
    if (e.强制 && 三餐.indexOf(来源) !== -1 && typeof e.小时 === "number") {
      if (!校验餐次时间窗(来源, e.小时)) {
        return { "来源": null, "结果": "未到餐点", "兜底": false };
      }
    }
    return { "来源": 来源, "结果": null, "兜底": false };
  }

  // ============ 达标 / 加成 ============

  function 每日是否达标(每日, 目标) {
    var d = 每日 || {}, t = 目标 || 每日目标;
    return (d.三餐 || []).length >= t.三餐
        && (d.喝水 || 0) >= t.喝水
        && (d.运动 || 0) >= t.运动;
  }

  // 家具列表元素可以是 id 字符串，也可以是 { 槽, id, x, z }。
  // 同一件家具只算一次；总加成封顶 0.5。
  function 家具加成(家具列表, 数据表) {
    var 表 = 数据表 || window.家具数据 || [];
    var 见过 = {}, 总 = 0;
    (家具列表 || []).forEach(function (项) {
      if (!项) return;
      var id = (typeof 项 === "string") ? 项 : 项.id;
      if (!id || 见过[id]) return;
      见过[id] = true;
      for (var i = 0; i < 表.length; i++) {
        if (表[i].id === id) { 总 += 表[i].加成; break; }
      }
    });
    return Math.min(总, 家具加成上限);
  }

  // ============ 默认数据 ============

  function 默认存档(数据表) {
    var 数据 = 数据表 || window.装扮数据 || {};
    var 已购 = [];
    Object.keys(数据).forEach(function (分类) {
      (数据[分类] || []).forEach(function (件) {
        if (件.价格 === 0) 已购.push(分类 + ":" + 件.id);
      });
    });
    return {
      "版本": 1, "经验": 0, "金币": 0,
      "形象": {
        "脸型": "脸-圆脸", "肤色": "色-自然", "眉": "眉-平眉", "眼": "眼-圆眼",
        "嘴": "嘴-微笑", "腮红": "红-无", "发型": "发-短发", "上衣": "衣-白T",
        "裤子": "裤-牛仔", "鞋": "鞋-帆布", "配饰": "饰-无"
      },
      "已购": 已购, "宠物": null, "上次打卡日": null, "连续天数": 0
    };
  }

  function 默认每日(日期) {
    return {
      "日期": 日期 || "", "三餐": [], "喝水": 0, "运动": 0,
      "已喂宠物": false, "达标": false
    };
  }

  function 默认场景() {
    return {
      "墙纸": "米白", "地板": "木地板", "相机": { "yaw": 0 },
      "家具": [null, null, null, null, null, null]
    };
  }

  function 复制存档(a) {
    var r = 浅拷(a || {});
    r.版本 = r.版本 || 1;
    r.经验 = Math.max(0, Number(r.经验) || 0);
    r.金币 = Math.max(0, Number(r.金币) || 0);
    r.形象 = 浅拷(r.形象 || {});
    r.已购 = (r.已购 || []).slice();
    r.宠物 = r.宠物 ? 浅拷(r.宠物) : null;
    r.上次打卡日 = r.上次打卡日 || null;
    r.连续天数 = Math.max(0, Number(r.连续天数) || 0);
    return r;
  }

  function 复制每日(d) {
    var r = 浅拷(d || {});
    r.三餐 = (r.三餐 || []).slice();
    r.喝水 = Math.max(0, Number(r.喝水) || 0);
    r.运动 = Math.max(0, Number(r.运动) || 0);
    r.已喂宠物 = !!r.已喂宠物;
    r.达标 = !!r.达标;
    return r;
  }

  // ============ 核心：结算打卡（单点入口） ============

  /**
   * 纯函数。严格按下列顺序执行，顺序不同结果不同（测试会对拍）：
   *   ① 来源归一化（加餐兜底 / 时间窗 / 非法来源）
   *   ② 去重与上限判定
   *   ③ 把来源计入每日
   *   ④ 查奖励表；金币乘 (1 + 家具加成)，经验永不加成
   *   ⑤ 经验、金币累加
   *   ⑥ 连签（仅三餐 / 喝水 / 运动触发）
   *   ⑦ 对比新旧等级，得出升了几级
   *   ⑧ 达标检查，未标记则递归结算一次「达标」（只递归一层）
   */
  function 结算打卡(存档, 每日, 来源, 额外) {
    var e = 额外 || {};
    var 新存档 = 复制存档(存档);
    var 新每日 = 复制每日(每日);
    var 今天 = e.今天 || 新每日.日期 || null;

    function 返回(结果, 获得, 升级数, 刚达标) {
      return {
        "存档": 新存档, "每日": 新每日,
        "获得": 获得 || 空获得(),
        "结果": 结果, "升了几级": 升级数 || 0,
        "是否刚达标": !!刚达标
      };
    }

    // ①
    var 归 = 归一化来源(来源, 新每日, e);
    if (归.结果) return 返回(归.结果, 空获得(), 0, false);
    var s = 归.来源;

    // ②
    if (三餐.indexOf(s) !== -1 && 新每日.三餐.indexOf(s) !== -1) {
      return 返回("已完成", 空获得(), 0, false);
    }
    if (s === "喝水" && 新每日.喝水 >= 每日上限.喝水) return 返回("已上限", 空获得(), 0, false);
    if (s === "运动" && 新每日.运动 >= 每日上限.运动) return 返回("已上限", 空获得(), 0, false);
    if (s === "达标" && 新每日.达标) return 返回("已完成", 空获得(), 0, false);

    // ③
    if (三餐.indexOf(s) !== -1) 新每日.三餐.push(s);
    else if (s === "喝水") 新每日.喝水 += 1;
    else if (s === "运动") 新每日.运动 += 1;
    else if (s === "达标") 新每日.达标 = true;

    // ④
    var 奖 = 奖励表[s];
    var 加成 = (typeof e.家具加成 === "number")
      ? Math.max(0, Math.min(e.家具加成, 家具加成上限)) : 0;
    var 本次经验 = 奖.经验;
    var 本次金币 = Math.round(奖.金币 * (1 + 加成));

    // ⑤
    var 旧经验 = 新存档.经验;
    新存档.经验 = 旧经验 + 本次经验;
    新存档.金币 = 新存档.金币 + 本次金币;

    // ⑥
    if (s !== "达标" && 今天) {
      新存档.连续天数 = 更新连续天数(新存档.上次打卡日, 今天, 新存档.连续天数);
      新存档.上次打卡日 = 今天;
    }

    // ⑦
    var 升了几级 = 由经验算等级(新存档.经验).等级 - 由经验算等级(旧经验).等级;

    // ⑧
    var 刚达标 = false;
    if (s !== "达标" && !新每日.达标 && 每日是否达标(新每日, e.目标 || 每日目标)) {
      var 递归 = 结算打卡(新存档, 新每日, "达标", {
        "今天": 今天, "家具加成": 加成, "目标": e.目标
      });
      新存档 = 递归.存档;
      新每日 = 递归.每日;
      本次经验 += 递归.获得.经验;
      本次金币 += 递归.获得.金币;
      升了几级 += 递归.升了几级;
      刚达标 = true;
    }

    return 返回(刚达标 ? "已达标" : (s === "达标" ? "已达标" : "已完成"),
                { "经验": 本次经验, "金币": 本次金币 }, 升了几级, 刚达标);
  }

  // ============ 宠物 ============

  /**
   * 心情由「用户今天做了几项」推导，不是喂没喂；不使用惩罚性文案。
   * 亲密度只增不减，喂食 +5（一天一次由调用方保证），封顶 100。
   */
  function 宠物心情(每日, 存档, 额外) {
    var d = 每日 || {}, a = 存档 || {}, e = 额外 || {};
    var 完成数 = 0;
    if ((d.三餐 || []).length > 0) 完成数 += 1;
    if ((d.喝水 || 0) > 0) 完成数 += 1;
    if ((d.运动 || 0) > 0) 完成数 += 1;
    var 心情 = 每日是否达标(d, e.目标 || 每日目标) ? "开心"
             : (完成数 >= 1 ? "一般" : "有点想你");
    var 亲密 = (a.宠物 && a.宠物.亲密度) || 0;
    if (e.今天喂过) 亲密 = Math.min(100, 亲密 + 5);
    return { "心情": 心情, "亲密度": Math.max(0, 亲密), "完成项数": 完成数 };
  }

  // ============ 场景（3D 房间与 2.5D 降级共用同一份纯数据） ============

  function 复制场景(s) {
    var r = 浅拷(s || 默认场景());
    r.相机 = 浅拷(r.相机 || { "yaw": 0 });
    var 家具 = (r.家具 || []).slice(0, 6);
    while (家具.length < 6) 家具.push(null);
    r.家具 = 家具.map(function (项) { return 项 ? 浅拷(项) : null; });
    return r;
  }

  function 场景槽位表(数据表) {
    var 表 = 数据表 || window.家具数据 || [];
    return 表.map(function (件, i) {
      return {
        "槽": i, "id": 件.id,
        "x": 件.默认位置.x, "z": 件.默认位置.z
      };
    });
  }

  // 同一件家具不能摆两个槽；同槽重复摆同一件视为幂等覆盖。
  function 摆放家具(场景, 槽, 家具id, 数据表) {
    var s = 复制场景(场景);
    var 表 = 数据表 || window.家具数据 || [];
    if (!(typeof 槽 === "number" && 槽 >= 0 && 槽 <= 5)) {
      return { "场景": s, "结果": "槽位无效" };
    }
    var 找到 = null;
    for (var i = 0; i < 表.length; i++) {
      if (表[i].id === 家具id) { 找到 = 表[i]; break; }
    }
    if (!找到) return { "场景": s, "结果": "无此家具" };
    for (var j = 0; j < 6; j++) {
      if (j !== 槽 && s.家具[j] && s.家具[j].id === 家具id) {
        return { "场景": s, "结果": "重复" };
      }
    }
    s.家具[槽] = {
      "槽": 槽, "id": 家具id,
      "x": 找到.默认位置.x, "z": 找到.默认位置.z
    };
    return { "场景": s, "结果": "已摆放" };
  }

  function 收起家具(场景, 槽) {
    var s = 复制场景(场景);
    if (typeof 槽 === "number" && 槽 >= 0 && 槽 <= 5) s.家具[槽] = null;
    return { "场景": s, "结果": "已收起" };
  }

  function 场景加成(场景, 数据表) {
    return 家具加成((场景 || {}).家具, 数据表);
  }

  // ============ 导出（供页面与 Python 对拍使用） ============

  window.养成系统 = {
    "奖励表": 奖励表,
    "每日目标": 每日目标,
    "每日上限": 每日上限,
    "合法来源": 合法来源,
    "餐次时间窗": 餐次时间窗,
    "满级": 满级,
    "每星经验": 每星经验,
    "家具加成上限": 家具加成上限,
    "满级累计经验": 满级累计经验,

    "升级所需经验": 升级所需经验,
    "由经验算等级": 由经验算等级,
    "星级": 星级,
    "解析日期": 解析日期,
    "相差天数": 相差天数,
    "更新连续天数": 更新连续天数,
    "校验餐次时间窗": 校验餐次时间窗,
    "归一化来源": 归一化来源,
    "每日是否达标": 每日是否达标,
    "家具加成": 家具加成,
    "结算打卡": 结算打卡,
    "宠物心情": 宠物心情,

    "默认存档": 默认存档,
    "默认每日": 默认每日,
    "默认场景": 默认场景,
    "复制场景": 复制场景,
    "场景槽位表": 场景槽位表,
    "摆放家具": 摆放家具,
    "收起家具": 收起家具,
    "场景加成": 场景加成
  };
})();
