"""逻辑复算测试：把 脚本.js 中的核心算法翻译成 Python 独立实现，
用多组边界数据验证目标卡路里、营养汇总、推荐规则是否符合 PRD。

这对应课程标准 U1「验收契约」与第 10 周「预期测试先于实现」的雏形。
"""
import json
import sys
from pathlib import Path

根 = Path(r"D:\lab\自选作品-web")
数据 = json.loads((根 / "数据" / "foods.json").read_text(encoding="utf-8"))

通过 = 0
失败 = 0


def 检查(名称, 实际, 期望):
    global 通过, 失败
    if 实际 == 期望:
        通过 += 1
        print(f"  ✓ {名称}：{实际}")
    else:
        失败 += 1
        print(f"  ✗ {名称}：实际 {实际}，期望 {期望}")


# ================= 被测逻辑（与 脚本.js 保持一致） =================
最低目标 = 1200
取整步长 = 10
人群系数 = {"减脂": 0.8, "增肌": 1.1, "控糖": 1.0, "均衡": 1.0}


def 计算基础代谢(性别, 体重, 身高, 年龄):
    基数 = 10 * 体重 + 6.25 * 身高 - 5 * 年龄
    return 基数 + 5 if 性别 == "男" else 基数 - 161


def 计算目标卡路里(性别, 体重, 身高, 年龄, 活动系数, 人群):
    bmr = 计算基础代谢(性别, 体重, 身高, 年龄)
    tdee = bmr * 活动系数
    调整后 = tdee * 人群系数[人群]
    取整后 = round(调整后 / 取整步长) * 取整步长
    是否上调 = 取整后 < 最低目标
    return 最低目标 if 是否上调 else 取整后


def 汇总营养(记录):
    合计 = {"卡路里": 0, "碳水": 0.0, "脂肪": 0.0, "膳食纤维": 0.0, "蛋白质": 0.0}
    for 条目 in 记录:
        for f in 合计:
            合计[f] += 条目[f]
    return {
        "卡路里": round(合计["卡路里"]),
        **{k: round(合计[k], 1) for k in ["碳水", "脂肪", "膳食纤维", "蛋白质"]},
    }


# ================= 测试用例 =================
print("【1】目标卡路里：常规场景")
检查("女22岁165cm55kg久坐减脂",
     计算目标卡路里("女", 55, 165, 22, 1.2, "减脂"), 1260)
检查("男25岁175cm70kg中度均衡",
     计算目标卡路里("男", 70, 175, 25, 1.55, "均衡"),
     round((10*70 + 6.25*175 - 5*25 + 5) * 1.55 / 10) * 10)
检查("男30岁180cm80kg高度增肌",
     计算目标卡路里("男", 80, 180, 30, 1.725, "增肌"),
     round((10*80 + 6.25*180 - 5*30 + 5) * 1.725 * 1.1 / 10) * 10)

print("\n【2】目标卡路里：边界与下限保护")
检查("极轻女性 减脂（应触发1200下限）",
     计算目标卡路里("女", 35, 150, 60, 1.2, "减脂"), 1200)
结果 = 计算目标卡路里("女", 35, 150, 60, 1.2, "减脂")
检查("下限保护结果 >= 1200", 结果 >= 1200, True)

# 取整规则：结果必须是 10 的倍数
for 参数 in [("男", 60, 170, 20, 1.2, "均衡"), ("女", 50, 160, 30, 1.375, "控糖"),
           ("男", 90, 185, 40, 1.55, "增肌"), ("女", 48, 158, 25, 1.725, "减脂")]:
    值 = 计算目标卡路里(*参数)
    检查(f"{_ if False else ''}取整规则 {参数[0]}{参数[1]}kg->{值} 是10的倍数", 值 % 10, 0)

print("\n【3】取整规则：四舍五入方向")
# 1257.84 -> 1260 （向上）；1249.9 -> 1250；1204.9 -> 1200
for 期望值, 说明 in [(1260, "1257.84→1260"), (1200, "1204.9→1200 且不低于下限")]:
    print(f"  · {说明}")

print("\n【4】营养汇总")
样例 = [
    数据[0],                                            # 鸡胸肉西兰花 320
    数据[5],                                            # 凉拌菠菜豆腐 180
]
合计 = 汇总营养(样例)
检查("两道菜卡路里合计", 合计["卡路里"], 320 + 180)
检查("两道菜碳水合计（1位小数）", 合计["碳水"], round(18.5 + 9.2, 1))
检查("两道菜蛋白质合计", 合计["蛋白质"], round(38.6 + 14.5, 1))
检查("空记录汇总为0", 汇总营养([])["卡路里"], 0)

print("\n【5】推荐规则：只出现该人群的菜")
for 人群 in ["减脂", "增肌", "控糖", "均衡"]:
    候选 = [c for c in 数据 if 人群 in c["人群"]]
    检查(f"{人群} 有可选食谱", len(候选) > 0, True)

print("\n【6】数据完整性：坐标级校验")
所有人群 = {"减脂", "增肌", "控糖", "均衡"}
覆盖 = {p: sum(1 for c in 数据 if p in c["人群"]) for p in 所有人群}
for p, n in 覆盖.items():
    print(f"  · {p}：{n} 道")
    检查(f"{p} 至少 3 道（够一次推荐）", n >= 3, True)

print(f"\n{'='*40}")
print(f"通过 {通过} 项，失败 {失败} 项")
sys.exit(0 if 失败 == 0 else 1)